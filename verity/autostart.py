def write_script() -> pathlib.Path:
    SCRIPT.parent.mkdir(parents=True, exist_ok=True)
    SCRIPT.write_text(_SCRIPT_BODY)
    SCRIPT.chmod(SCRIPT.stat().st_mode | stat.S_IEXEC | stat.S_IXGRP)
    return SCRIPT


